@compiles(CreateColumn, "oracle")
def _oracle_autoincrement(element, compiler, **kw):
    """Oracle does not number integer primary keys by itself (SQLite and Postgres do): give every single-column integer primary key an identity, for create_all and for Alembic alike."""
    text = compiler.visit_create_column(element, **kw)
    col = element.element
    pk = col.table.primary_key.columns if col.table is not None else []
    if (col.primary_key and len(pk) == 1 and isinstance(col.type, Integer) and col.autoincrement is not False
            and col.identity is None and col.default is None and col.server_default is None and "IDENTITY" not in text):
        clause = " GENERATED BY DEFAULT AS IDENTITY"
        text = text.replace(" NOT NULL", clause + " NOT NULL", 1) if " NOT NULL" in text else text + clause
    return text


def _oracle_bool_is(negate):
    """Oracle has no boolean type, so `col IS 1` is invalid SQL (ORA-00908). Render `.is_(True)` / `.is_(False)` as `= 1` / `= 0`."""
    def visit(self, binary, operator, **kw):
        from sqlalchemy.sql.elements import BindParameter, False_, True_
        r = binary.right
        val = True if isinstance(r, True_) else False if isinstance(r, False_) else (r.value if isinstance(r, BindParameter) and isinstance(r.value, bool) else None)
        if val is None:
            return self._generate_generic_binary(binary, " IS NOT " if negate else " IS ", **kw)
        return self.process(binary.left, **kw) + (" <> " if negate else " = ") + ("1" if val else "0")
    return visit


def _install_oracle_bool_is():
    from sqlalchemy.dialects.oracle.base import OracleCompiler
    OracleCompiler.visit_is__binary = _oracle_bool_is(False)
    OracleCompiler.visit_is_not_binary = _oracle_bool_is(True)


_install_oracle_bool_is()


